// Prepares the generated assets the Word (Office.js) add-in serves:
//
//   word-addin/src/euspell-engine.js  — the engine, reused verbatim from the
//                                        Apps Script port (same validated JS)
//   word-addin/src/euspell-data.js    — dictionary data as global strings (~5 MB)
//   word-addin/assets/icon-{16,32,80}.png — ribbon/taskpane icons
//
// All three are gitignored and regenerated. The engine + data are loaded by the
// taskpane (euspell-data.js before euspell-engine.js), exactly like in GAS, so
// the same Euspell.convertText runs in the Word webview.
//
// Run: npm run gen:word   (needs `npm run gen:lo` data)
import { readFileSync, writeFileSync, mkdirSync, existsSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'libreoffice', 'euspell', 'data');
const SRC = join(root, 'word-addin', 'src');
const ASSETS = join(root, 'word-addin', 'assets');

if (!existsSync(join(DATA, 'lexicon.csv'))) {
  console.error('Missing libreoffice/euspell/data — run "npm run gen:lo" first.');
  process.exit(1);
}
mkdirSync(SRC, { recursive: true });
mkdirSync(ASSETS, { recursive: true });

// 1. Engine: copy the Apps Script engine (identical browser-safe JS).
copyFileSync(join(root, 'apps-script', 'euspell-engine.gs'), join(SRC, 'euspell-engine.js'));

// 2. Data: the CSV/TSV strings as global JS constants.
const read = (f) => readFileSync(join(DATA, f), 'utf8');
const v = (name, content) => `var ${name} = ${JSON.stringify(content)};\n`;
const data =
  '// GENERATED by build/gen-word.js — do not edit. Dictionary data for euspell-engine.js.\n' +
  v('EUSPELL_LEXICON_CSV', read('lexicon.csv')) +
  v('EUSPELL_ABBR_CSV', read('abbreviations.csv')) +
  v('EUSPELL_CONTR_CSV', read('contractions.csv')) +
  v('EUSPELL_SVM_TSV', read('vvz_svm.tsv'));
writeFileSync(join(SRC, 'euspell-data.js'), data, 'utf8');

// 3. Icons: Office wants 16/32/80 px. Resize from the extension's icon.
const sizes = [16, 32, 80];
const sourceIcon = join(root, 'icons', '128.png');
try {
  const sharp = (await import('sharp')).default;
  await Promise.all(sizes.map((s) =>
    sharp(sourceIcon).resize(s, s).toFile(join(ASSETS, `icon-${s}.png`))));
} catch (e) {
  // Fallback: copy the source icon at each name (size mismatch is cosmetic).
  for (const s of sizes) copyFileSync(sourceIcon, join(ASSETS, `icon-${s}.png`));
  console.warn('[gen-word] sharp unavailable; copied unscaled icons');
}

console.log(`[gen-word] wrote engine + data (${(data.length / 1048576).toFixed(1)} MB) + icons to word-addin/`);
