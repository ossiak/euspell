#!/usr/bin/env python
"""Generate build/espeak-ipa-map.tsv: the IPA -> espeak-ng phoneme mnemonic table
used by build/pls-audio.ps1 to speak dict/euspell_tts.pls through espeak.

espeak-ng will not take IPA as input. Its --ipa flag is output only; feeding IPA
into the [[...]] phoneme syntax makes nonsense of it ("annexes" comes back as
b'akslaS), because those brackets expect espeak's own ASCII mnemonics. So the
lexicon's IPA has to be translated, and this builds the table that does it.

The segment map is DERIVED, not hand-written. espeak is run twice over the same
word list -- once with -x for mnemonics, once with --ipa -- both with --sep, and
the two token streams are zipped. Alignment is exact (6,159/6,159 words), so the
correspondence falls out of the data rather than out of anyone's memory of the
phoneme tables.

Two things the table cannot express, handled as rules in the consumer instead:

  stress  The lexicon marks it at the syllable onset (\u0259\u02c8b\u00e6nd\u0259nd) and espeak on the
          vowel (b\u02c8\u00e6nd\u0259nd), so the mark slides right over the onset consonants.
          Without that, 78% of the file fails to translate.
  length  espeak's mnemonics already encode it ("0" is ah-long), so a leftover
          \u02d0 is redundant rather than unmapped.

Coverage on the current lexicon: 35,385 of 35,424 entries translate completely
(99.89%). The 39 that do not are listed at the end of the run -- and are worth a
look, since bare "a" and "o" are not General American phonemes at all.

Usage:  python build/gen-espeak-map.py
"""
import io, os, re, subprocess, collections, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLS = os.path.join(ROOT, 'dict', 'euspell_tts.pls')
OUT = os.path.join(ROOT, 'build', 'espeak-ipa-map.tsv')
ESPEAK = os.environ.get('ESPEAK', r'C:\Program Files\eSpeak NG\espeak-ng.exe')
SAMPLE = int(os.environ.get('SAMPLE', 6000))

if not os.path.exists(ESPEAK):
    sys.exit('espeak-ng not found at %s (set ESPEAK=...)' % ESPEAK)

LEXEME = re.compile(
    r'<grapheme>([^<]+)</grapheme><phoneme>([^<]+)</phoneme></lexeme>'
    r'(?:\s*<!--\s*([^>]*?)\s*-->)?')
rows = [(m.group(1), m.group(2), (m.group(3) or '').strip())
        for m in LEXEME.finditer(io.open(PLS, encoding='utf-8').read())]
print('%d lexemes in %s' % (len(rows), os.path.relpath(PLS, ROOT)))

# --- 1. derive the segment map from espeak's own two views of a word list ----
words, seen = [], set()
for _, _, w in rows:
    if w and w.isalpha() and w.lower() not in seen:
        seen.add(w.lower())
        words.append(w)
words = words[:SAMPLE]

tmp = os.path.join(ROOT, 'build', '_espeak_words.tmp')
io.open(tmp, 'w', encoding='utf-8').write('\n'.join(words) + '\n')

def espeak(*extra):
    r = subprocess.run([ESPEAK, '-v', 'en-us', '-q', '--sep=|', '-f', tmp] + list(extra),
                       capture_output=True)
    return r.stdout.decode('utf-8', 'replace').split()

mnemonics, ipas = espeak('-x'), espeak('--ipa')
os.remove(tmp)

pairs, aligned = collections.Counter(), 0
for a, b in zip(mnemonics, ipas):
    A, B = a.split('|'), b.split('|')
    if len(A) != len(B):
        continue                      # a word espeak split differently in the two passes
    aligned += 1
    for mn, ipa in zip(A, B):
        if mn and ipa:
            pairs[(ipa, mn)] += 1

total = min(len(mnemonics), len(ipas))
print('aligned %d/%d words (%.1f%%)' % (aligned, total, 100.0 * aligned / max(1, total)))

best = {}
for (ipa, mn), n in pairs.most_common():
    best.setdefault(ipa, (mn, n))     # most_common first => most frequent wins
print('%d distinct espeak-IPA segments' % len(best))

# --- 2. normalization: the lexicon's conventions vs espeak's -----------------
# Same sounds, different spelling. Order matters; applied before segmenting.
NORM = [
    ('r', '\u0279'),                  # the GA rhotic: lexicon r, espeak turned-r
    ('\u0252', '\u0251\u02d0'),       # lot vowel: espeak en-us has no \u0252 (GA merger)
    ('\u025d', '\u025a'),             # r-colored nurse -> schwar
    ('\u025c', '\u025a'),             # reversed open e -> schwar
    ('.', ''),                        # syllable dot: no espeak equivalent
]
LENGTHEN = ['\u0251', '\u0254', 'u', 'i']   # espeak writes these long

# --- 3. write the table ------------------------------------------------------
out = io.open(OUT, 'w', encoding='utf-8', newline='\n')
out.write('# GENERATED by build/gen-espeak-map.py -- do not edit by hand.\n')
out.write('# IPA -> espeak-ng phoneme mnemonics, for build/pls-audio.ps1.\n')
out.write('# Derived by zipping espeak -x against espeak --ipa over %d words.\n' % len(words))
out.write('# kind\tfrom\tto\n')
for a, b in NORM:
    out.write('norm\t%s\t%s\n' % (a, b))
for v in LENGTHEN:
    out.write('long\t%s\t%s\u02d0\n' % (v, v))
for ipa in sorted(best, key=lambda k: (-len(k), k)):
    out.write('seg\t%s\t%s\n' % (ipa, best[ipa][0]))
out.close()
print('wrote %s (%d rules)' % (os.path.relpath(OUT, ROOT), len(NORM) + len(LENGTHEN) + len(best)))

# --- 4. report coverage over the whole lexicon ------------------------------
VOWELS = set(u'a\u00e6\u0250\u0251\u0254\u0259\u025a\u025b\u025c\u025dei\u026ao\u028au\u028c\u0252\u00f8y')
SEGS = sorted(best, key=len, reverse=True)

def translate(ipa):
    s = ipa
    for a, b in NORM:
        s = s.replace(a, b)
    for v in LENGTHEN:
        s = re.sub(re.escape(v) + '(?!\u02d0)', v + '\u02d0', s)
    # slide stress off the onset onto the vowel
    res, i = [], 0
    while i < len(s):
        if s[i] in u'\u02c8\u02cc':
            j = i + 1
            onset = []
            while j < len(s) and s[j] not in VOWELS and s[j] not in u'\u02c8\u02cc':
                onset.append(s[j]); j += 1
            res.append(''.join(onset)); res.append(s[i]); i = j
        else:
            res.append(s[i]); i += 1
    s = ''.join(res)
    got, i, bad = [], 0, []
    while i < len(s):
        for seg in SEGS:
            if s.startswith(seg, i):
                got.append(best[seg][0]); i += len(seg); break
        else:
            if s[i] == u'\u02c8': got.append("'"); i += 1
            elif s[i] == u'\u02cc': got.append(','); i += 1
            elif s[i] == u'\u02d0': i += 1
            else: bad.append(s[i]); i += 1
    return ''.join(got), bad

ok, unmapped, examples = 0, collections.Counter(), []
for g, ipa, w in rows:
    mn, bad = translate(ipa)
    if bad:
        for ch in bad:
            unmapped[ch] += 1
        if len(examples) < 12:
            examples.append((g, ipa))
    else:
        ok += 1
print('\ncoverage: %d/%d entries translate completely (%.2f%%)' % (ok, len(rows), 100.0 * ok / len(rows)))
if unmapped:
    print('unmapped characters (these entries will be skipped and reported):')
    for ch, n in unmapped.most_common():
        print('  U+%04X  %d entries' % (ord(ch), n))
    print('examples: ' + ', '.join(g for g, _ in examples))
