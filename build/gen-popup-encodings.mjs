// Generates src/popup/encodings.js — the encoding -> description table the
// popup's lookup shows in its tooltip.
//
// data/euspell_encoding.csv is the source of record for those descriptions (the
// integrity test already validates every lexicon encoding against it). Reading
// the CSV at runtime would mean shipping and parsing it in the popup, and would
// depend on data/ surviving into the packaged build; generating a 34-entry
// module instead costs nothing at runtime and cannot drift silently, because
// this script re-derives it.
//
// Run: npm run gen:popup-encodings

import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url);
const SRC = new URL('data/euspell_encoding.csv', ROOT);
const OUT = new URL('src/popup/encodings.js', ROOT);

/** Split one CSV line, honouring quoted fields. */
function fields(line) {
  const out = [];
  let cur = '';
  let quoted = false;
  for (let i = 0; i < line.length; i += 1) {
    const c = line[i];
    if (quoted) {
      if (c === '"' && line[i + 1] === '"') { cur += '"'; i += 1; } else if (c === '"') quoted = false;
      else cur += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { out.push(cur); cur = ''; } else cur += c;
  }
  out.push(cur);
  return out;
}

const lines = readFileSync(SRC, 'utf8').split(/\r?\n/).filter(Boolean);
const rows = lines.slice(1).map(fields);

const bad = rows.filter((r) => !/^\d{3}$/.test(r[0]) || !r[1]);
if (bad.length) throw new Error(`malformed rows in euspell_encoding.csv: ${JSON.stringify(bad)}`);

const body = rows
  .map(([code, description]) => `  [${parseInt(code, 10)}, ${JSON.stringify(description)}],`)
  .join('\n');

const out = `// Auto-generated by build/gen-popup-encodings.mjs — do not edit.
// Source: data/euspell_encoding.csv (${rows.length} codes). Descriptions are
// verbatim, so what the tooltip shows is what the table says.
//
// Keyed by the numeric encoding, because that is what a lexicon entry carries:
// compile-lexicon.js parses "012" to 12. Use pad() to get the printed form back.

/** @type {Map<number, string>} */
export const descriptions = new Map([
${body}
]);

/**
 * The three-digit printed form of a numeric encoding: 12 -> "012".
 * @param {number} encoding
 * @returns {string}
 */
export function pad(encoding) {
  return String(encoding).padStart(3, '0');
}
`;

writeFileSync(OUT, out, 'utf8');
console.log(`[euspell-build] Wrote src/popup/encodings.js (${rows.length} codes)`);
