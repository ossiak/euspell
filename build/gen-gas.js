// Emits apps-script/euspell-data.gs: the dictionary data the GAS engine parses,
// as global JS string constants. Sourced from the same files build/gen-lo.js
// produces (libreoffice/euspell/data), so run `npm run gen:lo` first.
//
// The file is ~5 MB (the lexicon dominates); it is gitignored and regenerated.
// Run: npm run gen:gas
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'libreoffice', 'euspell', 'data');
const OUT = join(root, 'apps-script');

if (!existsSync(join(DATA, 'lexicon.csv'))) {
  console.error('Missing libreoffice/euspell/data — run "npm run gen:lo" first.');
  process.exit(1);
}
mkdirSync(OUT, { recursive: true });

const read = (f) => readFileSync(join(DATA, f), 'utf8');
// JSON.stringify yields a valid, fully-escaped JS string literal.
const v = (name, content) => `var ${name} = ${JSON.stringify(content)};\n`;

const body =
  '// GENERATED by build/gen-gas.js — do not edit. Dictionary data for euspell-engine.gs.\n' +
  v('EUSPELL_LEXICON_CSV', read('lexicon.csv')) +
  v('EUSPELL_ABBR_CSV', read('abbreviations.csv')) +
  v('EUSPELL_CONTR_CSV', read('contractions.csv')) +
  v('EUSPELL_SVM_TSV', read('vvz_svm.tsv'));

const out = join(OUT, 'euspell-data.gs');
writeFileSync(out, body, 'utf8');
console.log(`[gen-gas] wrote ${out} (${(body.length / 1048576).toFixed(1)} MB)`);
