// Generates src/disambig/vvz-prior.js: a per-word noun/verb prior for the
// NN2|VVZ diatones (lexicon encodings 012 and 112), used to seed is_VVZ's vote
// (see route() in converter.js). The seed is a small signed integer in [-K, K]:
// positive = the word is usually a verb (VVZ), negative = usually a plural noun
// (NN2). Context cues can override it, so it is only a prior.
//
// Derived from the CLAWS-tagged corpus disambig/_corpus_012_112.txt (gitignored,
// large). Re-run with `npm run gen:prior` whenever that corpus changes. The
// OUTPUT module is committed so the build never needs the corpus.
//
// seed = clamp(round(K * (v - n) / (v + n + ALPHA)), -K, K), where v/n are the
// word's VVZ/NN2 counts. ALPHA shrinks low-count words toward 0 (less confident).
import { readFileSync, createReadStream, writeFileSync } from 'node:fs';
import { createInterface } from 'node:readline';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const K = 4;
const ALPHA = 5;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const LEX = join(root, 'data/euspell_lexicon.csv');
const CORPUS = join(root, 'disambig/_corpus_012_112.txt');
const OUT = join(root, 'src/disambig/vvz-prior.js');

// 1. Collect every 012/112 word from the lexicon.
const words = new Set();
for (const line of readFileSync(LEX, 'utf8').split(/\r?\n/)) {
  if (!line) continue;
  const c = line.split(',');
  if (c[2] === '012' || c[2] === '112') words.add(c[0].toLowerCase());
}

// 2. Count VVZ vs NN2 occurrences for those words across the corpus.
const vC = new Map(), nC = new Map();
const rl = createInterface({ input: createReadStream(CORPUS, 'utf8'), crlfDelay: Infinity });
for await (const line of rl) {
  if (!line) continue;
  for (const tk of line.split(' ')) {
    const u = tk.lastIndexOf('_');
    if (u <= 0) continue;
    const tag = tk.slice(u + 1);
    if (tag !== 'VVZ' && tag !== 'NN2') continue;
    const w = tk.slice(0, u).toLowerCase();
    if (!words.has(w)) continue;
    (tag === 'VVZ' ? vC : nC).set(w, ((tag === 'VVZ' ? vC : nC).get(w) || 0) + 1);
  }
}

// 3. Compute the seed for every word (0 when unseen or perfectly balanced).
const clamp = (x) => Math.max(-K, Math.min(K, x));
const rows = [];
let covered = 0, nonzero = 0;
for (const w of [...words].sort()) {
  const v = vC.get(w) || 0, n = nC.get(w) || 0;
  if (v + n > 0) covered++;
  const seed = v + n === 0 ? 0 : clamp(Math.round((K * (v - n)) / (v + n + ALPHA)));
  if (seed !== 0) nonzero++;
  rows.push([w, seed]);
}

// 4. Emit the module (all 012/112 words, so the table is complete).
const body = rows.map(([w, s]) => `  [${JSON.stringify(w)}, ${s}],`).join('\n');
const out = `/**
 * Per-word noun/verb prior for the NN2|VVZ diatones (encodings 012 and 112).
 * GENERATED by build/gen-vvz-prior.mjs from disambig/_corpus_012_112.txt — do not
 * edit by hand; re-run \`npm run gen:prior\`.
 *
 * Each entry maps a lowercase surface word to a seed in [-${K}, ${K}]: positive ⇒
 * usually a verb (VVZ), negative ⇒ usually a plural noun (NN2), 0 ⇒ no signal.
 * route() adds it to is_VVZ's context score, so strong context can still override.
 * ${rows.length} words (${covered} seen in the corpus, ${nonzero} with a non-zero prior).
 */
export const VVZ_PRIOR = new Map([
${body}
]);
`;
writeFileSync(OUT, out);
console.log(`[euspell-build] Wrote ${OUT}`);
console.log(`  ${rows.length} words, ${covered} seen, ${nonzero} non-zero (K=${K}, ALPHA=${ALPHA})`);
