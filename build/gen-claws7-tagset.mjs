// Vendors the UCREL CLAWS7 tagset into data/claws7-tagset.csv, which is the
// authority tests/lexicon-integrity.test.js checks the PoS column against —
// the same role data/euspell_encoding.csv plays for the encoding column.
//
// The upstream list lives outside this repo (Tagset/CLAWS7-tagset.txt, a copy of
// ucrel.lancs.ac.uk/claws7tags.html), so the copy here is what makes the guard
// portable. Re-run only to refresh against upstream; the tagset is stable.
//
// Run: npm run gen:claws7-tagset

import { readFileSync, writeFileSync } from 'node:fs';

const ROOT = new URL('..', import.meta.url);
const SRC = new URL('../Tagset/CLAWS7-tagset.txt', ROOT);
const OUT = new URL('data/claws7-tagset.csv', ROOT);

let text;
try {
  text = readFileSync(SRC, 'utf8');
} catch {
  throw new Error(
    `Cannot read ${SRC.pathname}. The upstream tagset lives outside this repo; `
    + 'data/claws7-tagset.csv is the committed copy and does not need regenerating '
    + 'unless UCREL change the list.',
  );
}

// "TAG<tab>description". Everything else in the file is the header, the prose
// note about ditto tags, or the source URL.
const rows = [];
for (const line of text.split(/\r?\n/)) {
  const m = /^([A-Z][A-Z0-9$]*)\t(.*)$/.exec(line);
  if (m) rows.push([m[1], m[2].trim()]);
}
if (rows.length < 100) throw new Error(`only ${rows.length} tags parsed — the source format has changed`);

const quote = (s) => (/[",]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s);
const body = rows.map(([tag, desc]) => `${tag},${quote(desc)}`).join('\n');

writeFileSync(
  OUT,
  'Tag,Description\n'
  + '# The UCREL CLAWS7 tagset, generated by build/gen-claws7-tagset.mjs from\n'
  + '# Tagset/CLAWS7-tagset.txt (ucrel.lancs.ac.uk/claws7tags.html).\n'
  + '#\n'
  + '# Any tag here may also carry a two-digit ditto suffix, marking a word in a\n'
  + '# multiword unit: the first digit is the length of the sequence, the second\n'
  + '# the position within it ("in terms of" = in_II31 terms_II32 of_II33).\n'
  + `${body}\n`,
  'utf8',
);
console.log(`[euspell-build] Wrote data/claws7-tagset.csv (${rows.length} tags)`);
