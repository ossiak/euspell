// Emits pages/euspell-pages.js: one self-contained JavaScript-for-Automation
// (JXA) script — the shared engine data + engine + the Pages glue, concatenated
// in that order (the same load order the Google Docs port uses). Run it on a Mac
// from the Script menu, an Automator Quick Action, or a Shortcut; it transforms
// the frontmost Pages document. See pages/README.md.
//
// It reuses the Apps Script data + engine verbatim (one engine, another host), so
// it needs gen:gas to have produced apps-script/euspell-data.gs first. The output
// is ~5 MB (the lexicon dominates) and gitignored.
//
// Run: npm run gen:pages
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'apps-script', 'euspell-data.gs');
const ENGINE = join(root, 'apps-script', 'euspell-engine.gs');
const GLUE = join(root, 'pages', 'euspell-pages-glue.js');
const OUT = join(root, 'pages', 'euspell-pages.js');

if (!existsSync(DATA)) {
  console.error('Missing apps-script/euspell-data.gs — run "npm run gen:gas" first.');
  process.exit(1);
}

const read = (f) => readFileSync(f, 'utf8');
const body = [
  '// GENERATED by build/gen-pages.js — do not edit.\n',
  '// euspell for Apple Pages (JXA) = euspell-data.gs + euspell-engine.gs + pages/euspell-pages-glue.js\n',
  read(DATA),
  '\n',
  read(ENGINE),
  '\n',
  read(GLUE),
].join('');

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, body, 'utf8');
console.log(`[gen-pages] wrote ${OUT} (${(body.length / 1048576).toFixed(1)} MB)`);
